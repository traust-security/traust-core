def test_servers_in_other_languages_are_coverage_gaps(tmp_path):
    fact = _fact(
        tmp_path,
        {
            "svc.py": "import grpc\nserver = grpc.server(pool)\n",
            "App.java": "Server s = ServerBuilder.forPort(8080).build();\n",
            "index.ts": "import * as grpc from '@grpc/grpc-js';\n",
        },
    )
    assert [g.system for g in fact.coverage_gaps] == ["java-grpc", "node-grpc", "python-grpc"]


def test_mask_comments_keeps_lines_and_strings():
    text = 'a := "//x" // c\n/* b\n c */ d `/* raw */`\n'
    masked = mask_comments(text)
    assert masked.count("\n") == text.count("\n")
    assert '"//x"' in masked and "`/* raw */`" in masked and "c */" not in masked


def test_the_matrix_is_one_fact_with_provenance(tmp_path):
    matrix = GrpcGuardMatrix(FixedClock(datetime(2026, 10, 26, tzinfo=UTC)))
    assert matrix.check().ready
    result = matrix.enumerate(ToolRequest(workspace=tmp_path))
    assert [type(f) for f in result.data] == [GrpcGuardFact]
    assert result.acquisition.provider == "grpc-guards"
